import { readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";

const root = process.cwd();
const openApiPath = join(root, "packages", "api-types", "src", "openapi.json");
const outputPath = join(root, "packages", "api-types", "src", "generated.ts");
const openapi = JSON.parse(readFileSync(openApiPath, "utf8"));
const schemas = openapi.components?.schemas ?? {};

function refName(ref) {
  return ref.split("/").at(-1);
}

function tsType(schema) {
  if (!schema) return "unknown";
  if (schema.$ref) return refName(schema.$ref);
  if (schema.anyOf) {
    return schema.anyOf.map(tsType).join(" | ");
  }
  if (schema.oneOf) {
    return schema.oneOf.map(tsType).join(" | ");
  }
  if (schema.allOf) {
    return schema.allOf.map(tsType).join(" & ");
  }
  if (schema.enum) {
    return schema.enum.map((value) => JSON.stringify(value)).join(" | ");
  }
  if (schema.type === "array") {
    return `${tsType(schema.items)}[]`;
  }
  if (schema.type === "object" || schema.properties) {
    const properties = schema.properties ?? {};
    const required = new Set(schema.required ?? []);
    const entries = Object.entries(properties).map(([key, value]) => {
      const optional = required.has(key) ? "" : "?";
      return `  ${JSON.stringify(key)}${optional}: ${tsType(value)};`;
    });
    if (entries.length === 0) return "Record<string, unknown>";
    return `{\n${entries.join("\n")}\n}`;
  }
  if (schema.type === "integer" || schema.type === "number") return "number";
  if (schema.type === "boolean") return "boolean";
  if (schema.type === "string") return "string";
  if (schema.type === "null") return "null";
  return "unknown";
}

const lines = [
  "// Generated by scripts/generate-api-types.mjs. Do not edit by hand.",
  "export type ApiSchemas = {"
];

for (const [name, schema] of Object.entries(schemas)) {
  lines.push(`  ${JSON.stringify(name)}: ${tsType(schema)};`);
}

lines.push("};", "");

for (const [name, schema] of Object.entries(schemas)) {
  lines.push(`export type ${name} = ${tsType(schema)};`, "");
}

lines.push("export type ApiPath =");
for (const path of Object.keys(openapi.paths ?? {})) {
  lines.push(`  | ${JSON.stringify(path)}`);
}
lines.push(";");

writeFileSync(outputPath, `${lines.join("\n")}\n`, "utf8");
console.log(`API_TYPES_GENERATED ${outputPath}`);
